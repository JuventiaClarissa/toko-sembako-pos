-- 1. TABEL PRODUK & STOK MULTI-GUDANG
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'garam', -- 'garam', 'minuman', 'sembako'
    unit TEXT NOT NULL DEFAULT 'Karung',    -- 'Karung 50kg', 'Bungkus 1kg', 'Dus', 'Bal'
    stock_toko NUMERIC(10, 2) NOT NULL DEFAULT 0,
    stock_gudang NUMERIC(10, 2) NOT NULL DEFAULT 0,
    cost_price NUMERIC(12, 2) NOT NULL DEFAULT 0, -- Harga Beli Modal (Khusus Pemilik)
    sell_price NUMERIC(12, 2) NOT NULL DEFAULT 0, -- Harga Jual Kasir
    min_stock_alert NUMERIC(10, 2) DEFAULT 5,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL TRANSAKSI PENJUALAN KASIR
CREATE TABLE IF NOT EXISTS transactions (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    invoice_no TEXT UNIQUE NOT NULL,
    transaction_date TIMESTAMPTZ DEFAULT NOW(),
    customer_name TEXT DEFAULT 'Umum (Standar)',
    customer_phone TEXT,
    payment_type TEXT NOT NULL DEFAULT 'tunai', -- 'tunai', 'bon', 'transfer'
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    paid_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    change_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    cashier_role TEXT DEFAULT 'pemilik',        -- 'pemilik' atau 'penjaga'
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. RINCIAN BARANG DALAM TRANSAKSI
CREATE TABLE IF NOT EXISTS transaction_items (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    transaction_id UUID REFERENCES transactions(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL,
    unit TEXT NOT NULL,
    qty NUMERIC(10, 2) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    cost_price NUMERIC(12, 2) DEFAULT 0 -- Dicatat snapshot saat transaksi untuk menghitung laba bersih riil
);

-- 4. TABEL BUKU BON & PIUTANG PELANGGAN
CREATE TABLE IF NOT EXISTS customer_debts (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    transaction_id UUID REFERENCES transactions(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT,
    total_debt NUMERIC(12, 2) NOT NULL DEFAULT 0,
    paid_debt NUMERIC(12, 2) NOT NULL DEFAULT 0,
    remaining_debt NUMERIC(12, 2) NOT NULL DEFAULT 0,
    due_date DATE,
    status TEXT NOT NULL DEFAULT 'belum_lunas', -- 'belum_lunas', 'lunas'
    items_summary TEXT,                        -- Misal: "10 Karung Garam Krosok"
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. RIWAYAT CICILAN & PELUNASAN BON
CREATE TABLE IF NOT EXISTS debt_payments (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    debt_id UUID REFERENCES customer_debts(id) ON DELETE CASCADE,
    payment_date TIMESTAMPTZ DEFAULT NOW(),
    amount_paid NUMERIC(12, 2) NOT NULL,
    remaining_after NUMERIC(12, 2) NOT NULL,
    payment_method TEXT DEFAULT 'tunai_laci', -- 'tunai_laci', 'transfer'
    received_by TEXT DEFAULT 'kasir',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. PENGELUARAN KAS, PRIVE, BEBAN, & KULAKAN (AMBIL UANG)
CREATE TABLE IF NOT EXISTS cash_movements (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    movement_type TEXT NOT NULL DEFAULT 'keluar', -- 'keluar' atau 'masuk'
    wallet_source TEXT NOT NULL DEFAULT 'laci_kasir', -- 'laci_kasir', 'modal_garam', 'bank'
    category TEXT NOT NULL, -- 'prive', 'beban_usaha', 'gaji_staf', 'supplier', 'kulakan', 'modal_awal'
    amount NUMERIC(12, 2) NOT NULL,
    notes TEXT,
    logged_by TEXT DEFAULT 'pemilik',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. LOG BUKA KARUNG GARAM (REPACK 50KG KE 1KG)
CREATE TABLE IF NOT EXISTS repack_logs (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    karung_opened NUMERIC(10, 2) NOT NULL,
    pack_produced NUMERIC(10, 2) NOT NULL,
    packaging_cost NUMERIC(12, 2) DEFAULT 5000,
    shrinkage_kg NUMERIC(10, 2) DEFAULT 0,
    shrinkage_percent NUMERIC(5, 2) DEFAULT 0,
    new_unit_cost NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. TUTUP KASIR HARIAN & REKONSILIASI FISIK
CREATE TABLE IF NOT EXISTS daily_closing (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    closing_date DATE NOT NULL DEFAULT CURRENT_DATE,
    system_cash NUMERIC(12, 2) NOT NULL,
    physical_cash NUMERIC(12, 2) NOT NULL,
    difference NUMERIC(12, 2) NOT NULL DEFAULT 0, -- 0 (Pas), >0 (Lebih), <0 (Kurang)
    notes TEXT,
    closed_by TEXT DEFAULT 'pemilik',
    closed_at TIMESTAMPTZ DEFAULT NOW()
);

